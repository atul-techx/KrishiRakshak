export function getCropMeta(name = '') {
  const lower = name.toLowerCase();
  for (const [k, v] of Object.entries(cropDict)) {
    if (lower.includes(k)) return v;
  }
  return { hi: name, mr: name, cat: 'vegetables', icon: '🌾', msp: null };
}

