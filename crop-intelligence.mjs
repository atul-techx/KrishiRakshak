// Sort entries by key length descending so longer specific names match first
const sortedCropEntries = Object.entries(cropDict).sort((a, b) => b[0].length - a[0].length);

export function getCropMeta(name = '') {
  const lower = name.toLowerCase().trim();
  for (const [k, v] of sortedCropEntries) {
    if (lower.includes(k)) return v;
  }
  return { en: name, hi: name, mr: name, cat: 'vegetables', icon: '🌾', msp: null };
}

// Ignore non-agricultural commodity noise from raw feeds
export const NON_CROP_ITEMS = new Set([
  'wood', 'firewood', 'timber', 'cowdung', 'dry leaves', 'jute twine', 'gunny bags', 'tobacco', 'hay', 'straw'
]);

export function isRealCrop(name = '') {
  const lower = name.toLowerCase().trim();
  if (NON_CROP_ITEMS.has(lower)) return false;
  if (lower.startsWith('wood') || lower.includes('firewood') || lower.includes('timber') || lower.includes('cowdung')) return false;
  return true;
}

