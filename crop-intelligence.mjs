export function transformAgmarkRecord(r, idx) {
  const meta = getCropMeta(r.commodity || '');
  const min = Math.round(Number(r.min_price) || 0);
  const max = Math.round(Number(r.max_price) || 0);
  const rawModal = Number(r.modal_price) || (min > 0 ? min : 0);
  const modal = Math.round(rawModal);

  let trend = 'stable';
  let change = 0;
  let changePct = '0%';
  if (max > min && modal >= min) {
    const mid = (min + max) / 2;
    change = Math.round(modal - mid);
    if (change !== 0) {
      const pct = Math.min(15, Math.abs((change / (modal || 1)) * 100)).toFixed(1);
      if (change > 0) {
        trend = 'up';
        changePct = `+${pct}%`;
      } else {
        trend = 'down';
        changePct = `-${pct}%`;
      }
    }
  }

  const msp = meta.msp;
  const rawMarket = (r.market || 'APMC').trim();
  const cleanMarket = rawMarket.replace(/\s+/g, ' ').replace(/\s*\([^)]*\)\s*$/, '').trim() || rawMarket;
  const district = (r.district || '').trim();
  const state = (r.state || '').trim();

  const advisoryEn = msp && modal >= msp
    ? `Trading ₹${modal - msp} above MSP (₹${msp}). Favourable auction return.`
    : msp && modal < msp
    ? `Below MSP (₹${msp}). Explore procurement centers or storage.`
    : `Official open APMC rate reported for ${cleanMarket}.`;
  const advisoryHi = msp && modal >= msp
    ? `MSP (₹${msp}) से ₹${modal - msp} अधिक भाव। बिक्री के लिए अच्छा समय।`
    : msp && modal < msp
    ? `MSP (₹${msp}) से कम दर। सरकारी खरीद केंद्र या भंडारण का विचार करें।`
    : `${cleanMarket} में आज का आधिकारिक दर्ज भाव।`;
  const advisoryMr = msp && modal >= msp
    ? `हमीभावापेक्षा (₹${msp}) ₹${modal - msp} जास्त भाव. चांगला नफा मिळण्याची शक्यता.`
    : msp && modal < msp
    ? `हमीभावापेक्षा (₹${msp}) कमी भाव. हमीभाव खरेदी केंद्राचा विचार करा.`
    : `${cleanMarket} मधील आजचा अधिकृत नोंदवलेला भाव.`;

  return {
    id: `agmark-${state.toLowerCase().replace(/\s+/g, '')}-${idx}`,
    commodity: meta.en,
    commodityHi: meta.hi,
    commodityMr: meta.mr,
    category: meta.cat,
    icon: meta.icon,
    market: cleanMarket,
    district,
    state,
    modalPrice: modal,
    minPrice: min || modal,
    maxPrice: max || modal,
    change,
    changePct,
    trend,
    arrival: r.arrival_date ? `APMC दर्ज (${r.arrival_date})` : 'APMC आवक',
    msp,
    advisoryEn,
    advisoryHi,
    advisoryMr,
    updatedAt: r.arrival_date || '13 Sep 2026'
  };
}

